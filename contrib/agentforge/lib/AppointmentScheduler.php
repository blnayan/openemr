<?php

/**
 * Schedules synthetic calendar appointments for the seeded demo patients.
 *
 * The Synthea CSV pack does not include calendar/appointment data, so the
 * OpenEMR calendar (`openemr_postcalendar_events`) stays empty after the
 * demo seed unless we generate appointments separately. This class fills
 * in a 4-week schedule across business hours so the calendar view actually
 * shows the demo patients on a believable day.
 *
 * Inserts go through OpenEMR's existing AppointmentService::insert so the
 * row gets a UUID and lands in the same shape the rest of the EHR expects
 * (visible to the calendar UI, the Today's Appointments widget, the
 * dashboard "upcoming" panel, and FHIR /Appointment).
 *
 * Schedule shape (deterministic given the same patient list + start date):
 *   - First day = today.
 *   - 4 weeks of weekdays (skip Sat/Sun) ≈ 20 working days.
 *   - Each weekday: 2–4 appointments at 15-min slots between 09:00 and 16:00,
 *     skipping the 12:00–13:00 lunch hour.
 *   - Patients round-robin across slots so every demo patient gets ≥2
 *     appointments and today specifically has 4–5 appointments (matches
 *     UC-1's "Dr. M between rooms" cadence).
 *
 * @package OpenEMR
 * @license https://github.com/openemr/openemr/blob/master/LICENSE GNU GPL 3
 */

declare(strict_types=1);

namespace OpenEMR\AgentForge\DemoSeed;

use OpenEMR\Services\AppointmentService;

final class AppointmentScheduler
{
    /** "Established Patient" — the openemr_postcalendar_categories seed id. */
    private const CATEGORY_ESTABLISHED = 9;

    private const DEFAULT_FACILITY_ID = 3;
    private const DEFAULT_PROVIDER_ID = 1;

    /** 30 minutes per appointment, expressed in seconds (pc_duration). */
    private const DURATION_SECONDS = 1800;

    /** Slots used each weekday (24-hour clock); lunch hour intentionally skipped. */
    private const SLOTS = [
        '09:00:00', '09:30:00', '10:00:00', '10:30:00', '11:00:00', '11:30:00',
        '13:00:00', '13:30:00', '14:00:00', '14:30:00', '15:00:00', '15:30:00',
    ];

    private const REASONS = [
        'Diabetes follow-up',
        'Hypertension recheck',
        'Annual physical',
        'Medication review',
        'Lab follow-up',
        'Post-discharge visit',
        'Anticoagulation INR check',
        'Lipid management',
        'Acute visit — URI',
        'Knee pain follow-up',
    ];

    private AppointmentService $appointments;

    public function __construct()
    {
        $this->appointments = new AppointmentService();
    }

    /**
     * Drop any prior demo appointments and write a fresh schedule.
     *
     * @param list<array{pid: int, name: string}> $patients
     * @return int number of appointments inserted
     */
    public function reschedule(array $patients, int $weeks = 4, ?\DateTimeImmutable $startDate = null): int
    {
        if ($patients === []) {
            return 0;
        }

        $this->wipeExisting(array_map(static fn(array $p): int => $p['pid'], $patients));

        $start = $startDate ?? new \DateTimeImmutable('today');
        $inserted = 0;
        $patientCursor = 0;
        $reasonCursor = 0;

        $endsAt = $start->modify(sprintf('+%d days', $weeks * 7));
        for ($day = $start; $day < $endsAt; $day = $day->modify('+1 day')) {
            $dow = (int) $day->format('N');
            if ($dow >= 6) {
                continue; // Saturday/Sunday
            }

            // 3 appointments most days; today and Mondays get 5 (busier).
            $isToday = $day->format('Y-m-d') === $start->format('Y-m-d');
            $count = $isToday ? 5 : ($dow === 1 ? 5 : 3);

            $slotsForDay = array_slice(self::SLOTS, 0, $count);
            foreach ($slotsForDay as $time) {
                $patient = $patients[$patientCursor % count($patients)];
                $reason  = self::REASONS[$reasonCursor % count(self::REASONS)];
                $patientCursor++;
                $reasonCursor++;

                $this->appointments->insert($patient['pid'], [
                    'pc_catid'             => self::CATEGORY_ESTABLISHED,
                    'pc_title'             => $reason,
                    'pc_duration'          => self::DURATION_SECONDS,
                    'pc_hometext'          => 'Demo appointment generated by AgentForge seeder.',
                    'pc_eventDate'         => $day->format('Y-m-d'),
                    'pc_apptstatus'        => '-',
                    'pc_startTime'         => $time,
                    'pc_facility'          => self::DEFAULT_FACILITY_ID,
                    'pc_billing_location'  => self::DEFAULT_FACILITY_ID,
                    'pc_aid'               => self::DEFAULT_PROVIDER_ID,
                    'pc_website'           => null,
                ]);
                $inserted++;
            }
        }

        return $inserted;
    }

    /**
     * Wipe every postcalendar event tied to the demo patients. We cannot just
     * `WHERE pc_pid IN (...)` because pc_pid is varchar — but we know the
     * narrow id range, so this is safe.
     *
     * @param list<int> $pids
     */
    private function wipeExisting(array $pids): void
    {
        if ($pids === []) {
            return;
        }
        $placeholders = implode(',', array_fill(0, count($pids), '?'));
        $stringPids = array_map('strval', $pids);
        sqlStatement(
            "DELETE FROM openemr_postcalendar_events WHERE pc_pid IN ($placeholders)",
            $stringPids
        );
    }
}
